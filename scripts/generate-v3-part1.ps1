## Bab 2: Prinsip dan Nilai Proyek

### 2.1 Sepuluh Nilai Inti

**1. Pelan tapi pasti dan presisi.**
Tidak terburu-buru. Setiap langkah diverifikasi.

**2. Satu langkah, satu verifikasi.**
Kerjakan satu hal, pastikan berhasil, baru lanjut.

**3. Fungsional dulu, cantik kemudian.**
Website yang berfungsi lebih penting dari website cantik.

**4. Jangan hapus sebelum audit.**
Sebelum menghapus file, audit dulu. Bisa jadi masih berguna.

**5. Keamanan tidak bisa dikompromikan.**
Token, password, API key tidak boleh masuk Git.

**6. Dokumentasi adalah sumber kebenaran.**
Bukan percakapan AI. Setiap keputusan harus tercatat.

**7. AI adalah tenaga bantu yang bisa diganti.**
Jangan bergantung pada satu AI.

**8. Think 19 million. Build for 1.**
Visi 19 juta, eksekusi 1 per 1.

**9. Setiap keputusan harus tercatat.**
Jika tidak tercatat, keputusan itu hilang.

**10. Jangan jatuh cinta pada visi sampai data membuktikannya.**
Visi boleh besar, tapi harus diuji dengan data nyata.

### 2.2 Prinsip Anti-Amnesia

**Masalah:**
AI (ChatGPT, Gemini, DeepSeek) mudah lupa konteks. Setiap sesi baru, harus jelaskan ulang. Kuota habis, harus pindah AI. Hasil: kerja berulang, tidak efisien.

**Solusi:**
Dokumentasi sebagai sumber kebenaran, bukan percakapan AI.

Setiap keputusan penting harus tercatat di dokumen. AI tidak perlu mengingat, cukup baca dokumen.

**Implementasi:**
- Setiap sesi kerja berakhir dengan update dokumentasi.
- Setiap sesi baru dimulai dengan baca dokumentasi.
- Setiap AI baru cukup baca dokumentasi, langsung paham.

### 2.3 Prinsip "Think 19 Million, Build for 1"

**Filosofi:**
- Jangan takut bermimpi besar (19 juta UMKM).
- Tapi eksekusi mulai dari 1.
- Jangan bangun untuk 19 juta sekaligus.
- Bangun untuk 1, lalu 10, lalu 100, dst.

**Cara Mengukur Progres:**
1 website sempurna → 10 website → 100 website → 1.000 website → 10.000 website → 100.000 website → 1 juta → 19 juta.

**Setiap Tahap Diukur:**
- Page load
- Ukuran HTML
- Ukuran gambar
- D1 reads
- D1 writes
- R2 storage
- Worker requests
- Biaya
- Error
- Performa Android murah
- Performa koneksi lambat

### 2.4 Prinsip "Jangan Jatuh Cinta pada Visi"

**Bahaya Terbesar:**
Jatuh cinta pada konsep sebelum membuktikan kebutuhan pasar.

**Pertanyaan yang Harus Dijawab:**
- Apakah pemilik UMKM benar-benar mau membuat NADI Node?
- Apakah seseorang benar-benar akan menggunakan NADI untuk mencari manusia?

**Prinsip:**
> Jangan percaya visi sebelum data membuktikannya.

**Tiga Lapisan Visi:**
1. **Yang sudah kuat secara konsep:** Nama, metafora, filosofi.
2. **Yang masuk akal tapi hipotesis:** 19 juta UMKM, UMKM mau gratis.
3. **Yang jangan dianggap pasti:** NADI pasti besar, pasti 19 juta Node.

